"""Generate main/font_data.c: anti-aliased 8-bit glyph bitmaps from Windows Segoe UI.

Run with the system Python (Pillow needed):  python tools/gen_fonts.py
The generated file is not tracked in git; it is rebuilt from the Windows font.
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont

FONTS = r"C:\Windows\Fonts"
# name, ttf, pixel size, characters (Latin-1) to include
SPECS = [
    ("f_lbl",  "segoeui.ttf", 12, [chr(c) for c in range(32, 127)] + ["\xb0", "\xb7"]),
    ("f_num",  "seguisb.ttf", 14, list("0123456789")),
    ("f_date", "segoeui.ttf", 17, [chr(c) for c in range(32, 127)] + ["\xb0", "\xb7"]),
    ("f_val",  "seguisb.ttf", 22, [chr(c) for c in range(32, 127)] + ["\xb0", "\xb7"]),
    ("f_temp", "seguisb.ttf", 30, list("0123456789-") + ["\xb0", "F", " "]),
    ("f_time", "seguisb.ttf", 22, list("0123456789: ")),
]

out = ["// GENERATED by tools/gen_fonts.py from Windows Segoe UI. Do not edit.",
       '#include "font.h"', ""]
for name, ttf, size, chars in SPECS:
    font = ImageFont.truetype(os.path.join(FONTS, ttf), size)
    data = bytearray()
    glyphs = []
    for code in range(32, 256):
        ch = chr(code)
        if ch not in chars:
            glyphs.append((0, 0, 0, 0, 0, 0))
            continue
        adv = int(round(font.getlength(ch)))
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = max(r - l, 0), max(b - t, 0)
        off = len(data)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=font, fill=255, anchor="ls")
            data += im.tobytes()
        glyphs.append((w, h, l, t, adv, off))
    out.append("static const uint8_t %s_alpha[] = {" % name)
    for i in range(0, len(data), 24):
        out.append("  " + ",".join(str(v) for v in data[i:i + 24]) + ",")
    if not data:
        out.append("  0")
    out.append("};")
    out.append("static const glyph_t %s_g[] = {" % name)
    for g in glyphs:
        out.append("  {%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    out.append("const font_t %s = { %s_g, %s_alpha };" % (name, name, name))
    out.append("")
    print("%-7s %2dpx  %6d bytes" % (name, size, len(data)))

here = os.path.dirname(os.path.abspath(__file__))
path = os.path.join(here, "..", "main", "font_data.c")
with open(path, "w", newline="\n") as f:
    f.write("\n".join(out))
print("wrote", os.path.normpath(path))
