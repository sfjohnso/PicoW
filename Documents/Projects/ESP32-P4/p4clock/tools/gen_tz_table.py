"""Generate main/tz_table.h: every IANA time zone name with its POSIX TZ rule.

The rule is the last line of each zone's file in the tzdata package. The clock uses the table to
turn the zone name that Open-Meteo returns for a location into a rule it can hand to tzset().

    pip install tzdata
    python tools/gen_tz_table.py

Greenland's rule contains a negative time ("M3.5.0/-1") which the C library on the board cannot
parse; it is rewritten to "/0" (the March changeover moves by one hour, on one night).
"""
import importlib.resources
import os
import re
import zoneinfo

import tzdata


def rule_for(iana):
    parts = iana.split("/")
    package = "tzdata.zoneinfo" + "".join("." + p for p in parts[:-1])
    data = importlib.resources.files(package).joinpath(parts[-1]).read_bytes()
    rule = data.rstrip(b"\n").rsplit(b"\n", 1)[-1].decode("ascii")
    assert data[:4] == b"TZif" and rule and len(rule) <= 63, iana
    return re.sub(r"/-\d+(?::\d+)*", "/0", rule)


zones = sorted(z for z in zoneinfo.available_timezones() if not z.startswith(("posix/", "right/")))
lines = ["// Generated by tools/gen_tz_table.py from tzdata %s. Sorted by name (strcmp order) for bsearch." % tzdata.IANA_VERSION,
         "static const struct { const char *name, *rule; } TZ_TABLE[] = {"]
lines += ['    {"%s", "%s"},' % (z, rule_for(z)) for z in zones]
lines.append("};")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "main", "tz_table.h")
with open(out, "w", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print(len(zones), "zones written to", os.path.normpath(out))
